const dicts: Record<Lang, Record<TKey, string>> = { ru, en };

// Дефолт до загрузки настроек из Dexie — 'ru', чтобы smoke и первый кадр
// приложения не мигали английским, пока LangApplier не подтянул settings.language.
let current: Lang = 'ru';
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(l: Lang): void {
  if (l === current) return;
  current = l;
  for (const fn of listeners) fn();
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Перевод по ключу с подстановкой {var} из vars. */
export function t(key: TKey, vars?: Record<string, string | number>): string {
  const raw = dicts[current][key];
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

/** Синхронный t() из любого компонента, без контекста и без обращения к БД на рендере. */
export function useT(): typeof t {
  useSyncExternalStore(subscribe, () => current);
  return t;
}

/** 'system' резолвится по navigator.language — иначе по явному выбору пользователя. */
export function resolveLang(setting: 'ru' | 'en' | 'system' | undefined): Lang {
  if (setting === 'ru' || setting === 'en') return setting;
  return navigator.language.startsWith('ru') ? 'ru' : 'en';
}
